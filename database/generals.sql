-- 三国志略 武将属性表

DROP TABLE IF EXISTS generals;
CREATE TABLE generals (
  id INT PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(20) NOT NULL,
  faction VARCHAR(10) NOT NULL COMMENT '阵营:魏/蜀/吴/群',
  atk_rank CHAR(1) NOT NULL COMMENT '武力等级',
  int_rank CHAR(1) NOT NULL COMMENT '智力等级',
  def_rank CHAR(1) NOT NULL COMMENT '统帅等级',
  spd_rank CHAR(1) NOT NULL COMMENT '速度等级',
  atk INT NOT NULL COMMENT '武力值',
  `int` INT NOT NULL COMMENT '智力值',
  def INT NOT NULL COMMENT '统帅值',
  spd INT NOT NULL COMMENT '速度值',
  hp INT NOT NULL DEFAULT 10000 COMMENT '生命',
  innate_skill VARCHAR(50) NOT NULL COMMENT '自带战法',
  skill_type VARCHAR(10) NOT NULL COMMENT '战法类型:主动/追击/指挥/被动',
  title VARCHAR(30) DEFAULT NULL COMMENT '称号'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='武将表';

